import { useEffect, useRef, useState } from 'react';
import Alert from '@mui/material/Alert';
import Button from '@mui/material/Button';
import Dialog from '@mui/material/Dialog';
import DialogActions from '@mui/material/DialogActions';
import DialogContent from '@mui/material/DialogContent';
import DialogContentText from '@mui/material/DialogContentText';
import DialogTitle from '@mui/material/DialogTitle';
import FormControlLabel from '@mui/material/FormControlLabel';
import Stack from '@mui/material/Stack';
import Switch from '@mui/material/Switch';

/** The client form's own field shape. A client has no display name; only its disabled state is editable here. */
export type ClientFormValues = {
  readonly isDisabled: boolean;
};

export type ClientFormDialogProps = {
  readonly open: boolean;
  readonly title: string;
  readonly submitLabel: string;
  readonly initialValues: ClientFormValues;
  readonly isSubmitting?: boolean;
  readonly error?: string | undefined;
  readonly onSubmit: (values: ClientFormValues) => void;
  readonly onCancel: () => void;
};

export const emptyClientFormValues: ClientFormValues = { isDisabled: false };

/**
 * Stateless client create/edit form rendered in a dialog. A client is server-identified (no display
 * name) and its settings/secrets are managed through their own endpoints, so the only field here is
 * the disabled toggle. The local field state is intrinsic to the control and reseeds on open, so the
 * component still renders in isolation under Storybook/RTL.
 */
export function ClientFormDialog({
  open,
  title,
  submitLabel,
  initialValues,
  isSubmitting = false,
  error,
  onSubmit,
  onCancel,
}: ClientFormDialogProps) {
  const [values, setValues] = useState<ClientFormValues>(initialValues);
  const wasOpenRef = useRef(open);

  useEffect(() => {
    if (open && !wasOpenRef.current) {
      setValues(initialValues);
    }
    wasOpenRef.current = open;
  }, [open, initialValues]);

  return (
    <Dialog open={open} onClose={onCancel} fullWidth maxWidth="sm">
      <DialogTitle>{title}</DialogTitle>
      <DialogContent>
        <Stack spacing={2} sx={{ mt: 1 }}>
          {error && (
            <Alert severity="error" data-testid="client-form-error">
              {error}
            </Alert>
          )}
          <DialogContentText component="div">
            The client id and secret are generated by the server; settings and secrets are managed
            after creation.
          </DialogContentText>
          <FormControlLabel
            control={
              <Switch
                checked={values.isDisabled}
                onChange={(event) => setValues({ isDisabled: event.target.checked })}
              />
            }
            label="Disabled"
          />
        </Stack>
      </DialogContent>
      <DialogActions>
        <Button onClick={onCancel} disabled={isSubmitting} data-testid="client-form-cancel">
          Cancel
        </Button>
        <Button
          variant="contained"
          onClick={() => onSubmit(values)}
          disabled={isSubmitting}
          data-testid="client-form-submit"
        >
          {isSubmitting ? 'Saving…' : submitLabel}
        </Button>
      </DialogActions>
    </Dialog>
  );
}
