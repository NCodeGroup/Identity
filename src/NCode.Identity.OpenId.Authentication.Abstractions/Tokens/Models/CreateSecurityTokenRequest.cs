using JetBrains.Annotations;
using NCode.Identity.OpenId.Authentication.Endpoints.Authorization.Messages;
using NCode.Identity.OpenId.Authentication.Subject;

namespace NCode.Identity.OpenId.Authentication.Tokens.Models;

/// <summary>
/// Contains the information required to create a security token.
/// </summary>
[PublicAPI]
public readonly record struct CreateSecurityTokenRequest
{
    /// <summary>
    /// Gets the <see cref="DateTimeOffset"/> when the token was created.
    /// </summary>
    public required DateTimeOffset CreatedWhen { get; init; }

    /// <summary>
    /// Gets the type of grant that is being used to generate the token.
    /// </summary>
    public required string GrantType { get; init; }

    /// <summary>
    /// Gets the <c>nonce</c> value that was provided by the client application.
    /// </summary>
    public string? Nonce { get; init; }

    /// <summary>
    /// Gets the <c>state</c> value that was provided by the client application.
    /// </summary>
    public string? State { get; init; }

    /// <summary>
    /// Gets the original scopes that were requested by the client application.
    /// </summary>
    public required IReadOnlyList<string> OriginalScopes { get; init; }

    /// <summary>
    /// Gets the effective scopes that will be used to generate the token.
    /// </summary>
    public required IReadOnlyList<string> EffectiveScopes { get; init; }

    /// <summary>
    /// Gets the <c>resource</c> indicators (RFC 8707) the access token targets, or <see langword="null"/> when none
    /// were requested. When non-empty, the access token's audience is narrowed to these resource servers.
    /// </summary>
    public IReadOnlyList<string>? Resources { get; init; }

    /// <summary>
    /// Gets the <c>code</c> value that was provided by the client application.
    /// </summary>
    public string? AuthorizationCode { get; init; }

    /// <summary>
    /// Gets the <c>access_token</c> value that was generated by the authorization server.
    /// </summary>
    public string? AccessToken { get; init; }

    /// <summary>
    /// Gets the <c>refresh_token</c> value that was generated by the authorization server.
    /// </summary>
    public string? RefreshToken { get; init; }

    /// <summary>
    /// Gets the opaque identifier of the refresh-token rotation family to issue this refresh token into, or
    /// <see langword="null"/> to begin a new family. On rotation, the refresh-token grant handler passes the prior
    /// token's lineage id so the whole family shares one identifier for reuse-detection revocation.
    /// </summary>
    public string? RefreshTokenLineageId { get; init; }

    /// <summary>
    /// Gets the claims requested via the OpenID Connect <c>claims</c> request parameter, or <see langword="null"/>
    /// when none were requested. Honored additively on top of the scope-driven claims.
    /// </summary>
    public IRequestClaims? RequestClaims { get; init; }

    /// <summary>
    /// Gets a value indicating whether the <c>auth_time</c> claim is required in the ID token because the request made
    /// it mandatory (a <c>max_age</c> request or an essential <c>auth_time</c> claim request, OpenID Connect Core 1.0
    /// §2 and §5.5.1.1). When <see langword="true"/>, the ID token includes <c>auth_time</c> regardless of the
    /// <c>always_include_auth_time</c> setting.
    /// </summary>
    public bool AuthTimeRequired { get; init; }

    /// <summary>
    /// Gets the <see cref="SubjectAuthentication"/> that contains the information about the authenticated end-user.
    /// </summary>
    public SubjectAuthentication? SubjectAuthentication { get; init; }

    /// <summary>
    /// Gets the sender-constraining <see cref="TokenConfirmation"/> (DPoP <c>jkt</c> / mutual-TLS <c>x5t#S256</c>) to
    /// embed as the access token's <c>cnf</c> claim, or <see cref="TokenConfirmation.None"/> when the token is a plain
    /// bearer token.
    /// </summary>
    public TokenConfirmation Confirmation { get; init; }

    /// <summary>
    /// Gets additional claims that will be included in the generated token.
    /// </summary>
    public IReadOnlyDictionary<string, object>? ExtraPayloadClaims { get; init; }

    /// <summary>
    /// Gets additional claims that will be included in the signature header.
    /// </summary>
    public IReadOnlyDictionary<string, object>? ExtraSignatureHeaderClaims { get; init; }

    /// <summary>
    /// Gets additional claims that will be included in the encryption header.
    /// </summary>
    public IReadOnlyDictionary<string, object>? ExtraEncryptionHeaderClaims { get; init; }
}
