using System.ComponentModel.DataAnnotations;
using Microsoft.EntityFrameworkCore;
using NCode.Identity.OpenId.Persistence.EntityFramework.Configuration;
using NCode.Identity.Persistence;
using NCode.Identity.Secrets.Persistence;
using NCode.Identity.Secrets.Persistence.DataContracts;

namespace NCode.Identity.OpenId.Persistence.EntityFramework.Core.Entities;

/// <summary>
/// Represents an entity framework data contract for an <c>OAuth</c> or <c>OpenID Connect</c> secret.
/// The complimentary DTO for this entity is <see cref="PersistedSecret"/>.
/// </summary>
[Index(nameof(NormalizedSecretId), IsUnique = true)]
public sealed class SecretEntity : ISupportConcurrencyToken
{
    /// <summary>
    /// Gets the surrogate identifier for this entity.
    /// </summary>
    [Key]
    [UseIdGenerator]
    public required long Id { get; init; }

    /// <summary>
    /// Gets the natural key for this entity.
    /// </summary>
    [Unicode(false)]
    [MaxLength(MaxLengths.ResourceId)]
    public required string SecretId { get; init; }

    /// <summary>
    /// Gets the value of <see cref="SecretId"/> in uppercase so that lookups can be sargable for DBMS
    /// engines that don't support case-insensitive indices.
    /// </summary>
    [Unicode(false)]
    [MaxLength(MaxLengths.ResourceId)]
    public required string NormalizedSecretId { get; init; }

    /// <summary>
    /// Gets the key identifier (<c>kid</c>) the key is selected by, or <c>null</c> when the key is identified by its
    /// <see cref="SecretId"/>. A <c>kid</c> is unique among its owner's keys, not across owners, so it is not indexed.
    /// </summary>
    [MaxLength(SecretMaxLengths.KeyId)]
    public required string? KeyId { get; init; }

    //

    /// <inheritdoc />
    [Unicode(false)]
    [MaxLength(MaxLengths.ConcurrencyToken)]
    [ConcurrencyCheck]
    public required string ConcurrencyToken { get; set; }

    /// <summary>
    /// Gets or sets the intended use for this secret. This property is optional and may be <c>null</c> to
    /// indicate that this secret is intended for use with any compatible algorithm.
    /// Valid values are defined in RFC 7517 Section 4.2:
    /// https://tools.ietf.org/html/rfc7517#section-4.2
    /// </summary>
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.Use)]
    public required string? Use { get; set; }

    /// <summary>
    /// Gets or sets the intended algorithm for use with this secret. This property is optional and may be
    /// <c>null</c> to indicate that this secret is intended for use with any compatible algorithm.
    /// </summary>
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.Algorithm)]
    public required string? Algorithm { get; set; }

    /// <summary>
    /// Gets the <see cref="DateTimeOffset"/> when this secret was created.
    /// </summary>
    public required DateTimeOffset CreatedWhen { get; init; }

    /// <summary>
    /// Gets or sets the <see cref="DateTimeOffset"/> when this secret's active window opens and it starts to sign or
    /// encrypt. Never before <see cref="CreatedWhen"/>.
    /// </summary>
    // See ADR-1403.
    public required DateTimeOffset ActivatesWhen { get; set; }

    /// <summary>
    /// Gets or sets the <see cref="DateTimeOffset"/> when this secret's active window closes and it stops signing or
    /// encrypting, while it still verifies or decrypts until <see cref="ExpiresWhen"/>. Never before
    /// <see cref="ActivatesWhen"/>, never after <see cref="ExpiresWhen"/>.
    /// </summary>
    // See ADR-1403.
    public required DateTimeOffset RetiresWhen { get; set; }

    /// <summary>
    /// Gets or sets the <see cref="DateTimeOffset"/> when this secret expires and is no longer valid.
    /// </summary>
    public required DateTimeOffset ExpiresWhen { get; set; }

    /// <summary>
    /// Gets a value that specifies the type of secret.
    /// See <see cref="SecretTypes"/> for possible values.
    /// </summary>
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.SecretType)]
    public required string SecretType { get; init; }

    /// <summary>
    /// Gets a value that specifies how the stored key material is encoded — an axis orthogonal to
    /// <see cref="SecretType"/> that distinguishes private (<c>PKCS#8</c>) from public (SPKI) asymmetric material.
    /// See <see cref="NCode.Identity.Secrets.SecretEncodings"/> for possible values.
    /// </summary>
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.SecretEncoding)]
    public required string SecretEncoding { get; init; }

    /// <summary>
    /// Gets a value that specifies where the secret's material came from: generated by the server or supplied by a
    /// caller. See <see cref="SecretOrigins"/> for possible values.
    /// </summary>
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.Origin)]
    public required string Origin { get; init; }

    /// <summary>
    /// Gets the name of the component that manages the secret's lifecycle on its own, or <c>null</c> when the secret
    /// keeps the lifecycle its creator gave it. See <see cref="PersistedSecret.ManagedBy"/>.
    /// </summary>
    // See ADR-1404.
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.ManagedBy)]
    public required string? ManagedBy { get; init; }

    /// <summary>
    /// Gets the size, in bits, of the key material.
    /// For asymmetric keys, this is the size of the modulus.
    /// For symmetric keys, this is the size of the actual key material.
    /// </summary>
    public required int KeySizeBits { get; init; }

    /// <summary>
    /// Gets or sets the base64url encoded value of the key material. The material is immutable; a rewrap replaces
    /// the envelope that protects it.
    /// </summary>
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.EncodedValue)]
    public required string EncodedValue { get; set; }

    /// <summary>
    /// Gets the base64url-encoded <c>SubjectPublicKeyInfo</c> DER of the public half of a private asymmetric key, or
    /// <c>null</c> when the secret holds no private asymmetric key.
    /// </summary>
    // See ADR-1268.
    [Unicode(false)]
    [MaxLength(SecretMaxLengths.PublicKey)]
    public required string? PublicKey { get; init; }
}
