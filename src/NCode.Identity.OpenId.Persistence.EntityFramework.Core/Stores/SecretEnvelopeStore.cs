using Microsoft.EntityFrameworkCore;
using NCode.Identity.OpenId.Persistence.DataContracts;
using NCode.Identity.OpenId.Persistence.EntityFramework.Core.Entities;
using NCode.Identity.OpenId.Persistence.Stores;
using NCode.Identity.Secrets.Persistence.Protection;
using NCode.Persistence.Stores;

namespace NCode.Identity.OpenId.Persistence.EntityFramework.Core.Stores;

/// <summary>
/// Provides a default implementation of <see cref="ISecretEnvelopeStore"/> that uses Entity Framework Core for
/// persistence. It reads the secrets of an owner through the join rows of the tenant, its clients and its resource
/// servers, or of the server, and rewrites only the protected value of a secret.
/// </summary>
/// <remarks>
/// This store does not save changes. The caller's store manager commits them. The queries ignore the tenant-scoping
/// filter because the owner names the tenant explicitly.
/// </remarks>
// See ADR-1407.
internal class SecretEnvelopeStore(IStoreProvider storeProvider, OpenIdDbContext openIdDbContext)
    : ISecretEnvelopeStore
{
    private IStoreProvider StoreProvider { get; } = storeProvider;

    private OpenIdDbContext DbContext { get; } = openIdDbContext;

    /// <inheritdoc />
    public object? GetService(Type serviceType) => StoreProvider.GetService(serviceType);

    /// <inheritdoc />
    public TStore GetStore<TStore>()
        where TStore : IStore => StoreProvider.GetStore<TStore>();

    /// <inheritdoc />
    public async ValueTask<PagedResult<PersistedProtectedValue>> GetPageAsync(
        SecretOwner owner,
        IReadOnlyCollection<string> valuePrefixes,
        PageRequest page,
        CancellationToken cancellationToken
    )
    {
        var (prefixes, length) = ValidatePrefixes(valuePrefixes, nameof(valuePrefixes));

        var query = GetOwnerSecrets(owner);
        if (query is null)
            return new PagedResult<PersistedProtectedValue> { Items = [], NextCursor = null };

        // Only the rows under the requested keys leave the database (ADR-1407). The length guard keeps a provider that
        // evaluates Substring in memory from throwing on a shorter value.
        query = query.Where(entity =>
            entity.EncodedValue.Length >= length
            && prefixes.Contains(entity.EncodedValue.Substring(0, length))
        );

        var afterId = KeysetCursor.Decode(page.Cursor);
        if (afterId is { } id)
            query = query.Where(entity => entity.Id > id);

        // Fetch one extra row so a full page signals that another page exists.
        var entities = await query
            .OrderBy(entity => entity.Id)
            .Take(page.Limit + 1)
            .Select(entity => new
            {
                entity.Id,
                entity.SecretId,
                entity.EncodedValue,
                entity.ConcurrencyToken,
            })
            .ToListAsync(cancellationToken);

        var hasMore = entities.Count > page.Limit;
        var count = hasMore ? page.Limit : entities.Count;

        return new PagedResult<PersistedProtectedValue>
        {
            Items = entities
                .Take(count)
                .Select(entity => new PersistedProtectedValue
                {
                    RecordId = entity.SecretId,
                    ItemId = entity.SecretId,
                    ProtectedValue = entity.EncodedValue,
                    ConcurrencyToken = entity.ConcurrencyToken,
                })
                .ToList(),
            NextCursor = hasMore ? KeysetCursor.Encode(entities[count - 1].Id) : null,
        };
    }

    /// <inheritdoc />
    public async ValueTask<bool> UpdateAsync(
        PersistedProtectedValue value,
        CancellationToken cancellationToken
    )
    {
        var normalizedSecretId = value.RecordId.ToLowerInvariant();
        var entity = await DbContext
            .Secrets.Where(secret => secret.NormalizedSecretId == normalizedSecretId)
            .SingleOrDefaultAsync(cancellationToken);
        if (entity is null)
            return false;

        if (
            !string.Equals(
                value.ConcurrencyToken,
                entity.ConcurrencyToken,
                StringComparison.Ordinal
            )
        )
        {
            throw new StoreConcurrencyException(
                $"The secret with SecretId='{value.RecordId}' has been modified by another process. Please reload and try again."
            );
        }

        // The row-level ConcurrencyToken is regenerated by the interceptor on save (ADR-1012). The record that owns the
        // secret gets a new secrets token so that every replica reloads its secrets.
        entity.EncodedValue = value.ProtectedValue;

        await BumpOwnerTokenAsync(entity.Id, cancellationToken);
        return true;
    }

    // Copies the prefixes and checks that there is at least one and that they share a length.
    private static (List<string> Prefixes, int Length) ValidatePrefixes(
        IReadOnlyCollection<string> prefixes,
        string paramName
    )
    {
        var list = new List<string>(prefixes);
        if (list.Count == 0 || list[0].Length == 0)
            throw new ArgumentException("At least one non-empty prefix is required.", paramName);

        var length = list[0].Length;
        if (list.Any(prefix => prefix.Length != length))
            throw new ArgumentException("The prefixes must all have the same length.", paramName);

        return (list, length);
    }

    // Selects the secrets of an owner, or null for an owner type that holds none.
    private IQueryable<SecretEntity>? GetOwnerSecrets(SecretOwner owner)
    {
        var normalizedOwnerId = owner.OwnerId.ToLowerInvariant();

        if (
            string.Equals(
                owner.OwnerType,
                SecretOwnerTypes.Tenant,
                StringComparison.OrdinalIgnoreCase
            )
        )
        {
            // Extension properties cannot appear in an expression tree, so the join rows are taken beforehand.
            var tenantSecrets = DbContext.TenantSecrets.IgnoreQueryFilters();
            var clientSecrets = DbContext.ClientSecrets.IgnoreQueryFilters();
            var resourceServerSecrets = DbContext.ResourceServerSecrets.IgnoreQueryFilters();

            return DbContext
                .Secrets.AsNoTracking()
                .Where(secret =>
                    tenantSecrets.Any(join =>
                        join.SecretId == secret.Id && join.NormalizedTenantId == normalizedOwnerId
                    )
                    || clientSecrets.Any(join =>
                        join.SecretId == secret.Id && join.NormalizedTenantId == normalizedOwnerId
                    )
                    || resourceServerSecrets.Any(join =>
                        join.SecretId == secret.Id && join.NormalizedTenantId == normalizedOwnerId
                    )
                );
        }

        if (
            string.Equals(
                owner.OwnerType,
                SecretOwnerTypes.Server,
                StringComparison.OrdinalIgnoreCase
            )
        )
        {
            var serverSecrets = DbContext.ServerSecrets;

            return DbContext
                .Secrets.AsNoTracking()
                .Where(secret =>
                    serverSecrets.Any(join =>
                        join.SecretId == secret.Id
                        && join.Server.NormalizedServerId == normalizedOwnerId
                    )
                );
        }

        return null;
    }

    // Gives the record that owns a secret, which is found through the join tables, a new secrets concurrency token.
    private async ValueTask BumpOwnerTokenAsync(long secretId, CancellationToken cancellationToken)
    {
        var token = Guid.NewGuid().ToString("N");

        var tenant = await DbContext
            .TenantSecrets.IgnoreQueryFilters()
            .Where(join => join.SecretId == secretId)
            .Select(join => join.Tenant)
            .FirstOrDefaultAsync(cancellationToken);
        if (tenant is not null)
        {
            tenant.SecretsConcurrencyToken = token;
            return;
        }

        var client = await DbContext
            .ClientSecrets.IgnoreQueryFilters()
            .Where(join => join.SecretId == secretId)
            .Select(join => join.Client)
            .FirstOrDefaultAsync(cancellationToken);
        if (client is not null)
        {
            client.SecretsConcurrencyToken = token;
            return;
        }

        var resourceServer = await DbContext
            .ResourceServerSecrets.IgnoreQueryFilters()
            .Where(join => join.SecretId == secretId)
            .Select(join => join.ResourceServer)
            .FirstOrDefaultAsync(cancellationToken);
        if (resourceServer is not null)
        {
            resourceServer.SecretsConcurrencyToken = token;
            return;
        }

        var server = await DbContext
            .ServerSecrets.Where(join => join.SecretId == secretId)
            .Select(join => join.Server)
            .FirstOrDefaultAsync(cancellationToken);
        if (server is not null)
            server.SecretsConcurrencyToken = token;
    }
}
