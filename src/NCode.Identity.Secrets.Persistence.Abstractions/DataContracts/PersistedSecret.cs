using System.ComponentModel.DataAnnotations;
using System.Diagnostics.CodeAnalysis;
using JetBrains.Annotations;
using NCode.Identity.Persistence;

namespace NCode.Identity.Secrets.Persistence.DataContracts;

/// <summary>
/// Contains the data for a persisted secret. A record, so a change to a secret's metadata or lifecycle is a
/// <c>with</c> copy that keeps every other member, its identity, concurrency token and key material included.
/// </summary>
[PublicAPI]
[ExcludeFromCodeCoverage]
public sealed record PersistedSecret : ISupportResource, ISupportSecretId, ISupportConcurrencyToken
{
    /// <summary>
    /// Gets the prefix for the resource type.
    /// </summary>
    [MaxLength(MaxLengths.ResourceType)]
    public const string ResourceTypePrefix = SecretResourceTypes.Secret;

    /// <inheritdoc/>
    [MaxLength(MaxLengths.ResourceType)]
    public string ResourceType => ResourceTypePrefix;

    /// <inheritdoc/>
    [MaxLength(MaxLengths.ResourceId)]
    public string ResourceId => SecretId;

    /// <inheritdoc/>
    [MaxLength(MaxLengths.ResourceId)]
    public required string SecretId { get; init; }

    /// <summary>
    /// Gets the key identifier (<c>kid</c>) the key is selected by, or <c>null</c> when the key is identified by its
    /// <see cref="SecretId"/>. A key registered by its owner (for example a client's public key) keeps the
    /// <c>kid</c> it was registered with, which is unique among its owner's keys but not across owners; a key the
    /// server generates is identified by its <see cref="SecretId"/>.
    /// </summary>
    [MaxLength(SecretMaxLengths.KeyId)]
    public string? KeyId { get; init; }

    /// <inheritdoc/>
    [MaxLength(MaxLengths.ConcurrencyToken)]
    public string ConcurrencyToken { get; set; } = string.Empty;

    //

    /// <summary>
    /// Gets the intended use for this secret. This property is optional and may be <c>null</c> to
    /// indicate that this secret is intended for use with any compatible algorithm.
    /// See <see cref="SecretKeyUses"/> for possible values.
    /// </summary>
    [MaxLength(SecretMaxLengths.Use)]
    public required string? Use { get; init; }

    /// <summary>
    /// Gets the intended algorithm for use with this secret. This property is optional and may be
    /// <c>null</c> to indicate that this secret is intended for use with any compatible algorithm.
    /// </summary>
    [MaxLength(SecretMaxLengths.Algorithm)]
    public required string? Algorithm { get; init; }

    /// <summary>
    /// Gets the <see cref="DateTimeOffset"/> when this secret was created, which opens its validity window.
    /// </summary>
    public required DateTimeOffset CreatedWhen { get; init; }

    /// <summary>
    /// Gets the <see cref="DateTimeOffset"/> when this secret's active window opens: from then on the secret signs or
    /// encrypts. A key published ahead of its use carries a future value; a secret with no lifecycle of its own, such
    /// as a client's shared secret, is active from <see cref="CreatedWhen"/>. Never before <see cref="CreatedWhen"/>.
    /// </summary>
    // See ADR-1403.
    public required DateTimeOffset ActivatesWhen { get; init; }

    /// <summary>
    /// Gets the <see cref="DateTimeOffset"/> when this secret's active window closes: from then on the secret signs
    /// and encrypts nothing, while it still verifies and decrypts until <see cref="ExpiresWhen"/>. A secret with
    /// no lifecycle of its own retires when it expires. Never before <see cref="ActivatesWhen"/>, never after
    /// <see cref="ExpiresWhen"/>.
    /// </summary>
    // See ADR-1403.
    public required DateTimeOffset RetiresWhen { get; init; }

    /// <summary>
    /// Gets the <see cref="DateTimeOffset"/> when this secret expires: its validity window closes, so it neither
    /// verifies nor decrypts, is not published, and does not authenticate.
    /// </summary>
    public required DateTimeOffset ExpiresWhen { get; init; }

    /// <summary>
    /// Gets a value that specifies the type of secret.
    /// See <see cref="SecretTypes"/> for possible values.
    /// </summary>
    [MaxLength(SecretMaxLengths.SecretType)]
    public required string SecretType { get; init; }

    /// <summary>
    /// Gets a value that specifies how the stored key material is encoded — an axis orthogonal to
    /// <see cref="SecretType"/> that distinguishes private (<c>PKCS#8</c>) from public (SPKI) asymmetric material.
    /// See <see cref="SecretEncodings"/> for possible values.
    /// </summary>
    // See ADR-1104.
    [MaxLength(SecretMaxLengths.SecretEncoding)]
    public required string SecretEncoding { get; init; }

    /// <summary>
    /// Gets a value that specifies where the secret's material came from: generated by the server or supplied by a
    /// caller. See <see cref="SecretOrigins"/> for possible values.
    /// </summary>
    // See ADR-1391.
    [MaxLength(SecretMaxLengths.Origin)]
    public required string Origin { get; init; }

    /// <summary>
    /// Gets the name of the component that manages the secret's lifecycle on its own, such as the tenant key rollover,
    /// which retires and removes the keys it provisioned; or <c>null</c> when the secret keeps the lifecycle its
    /// creator gave it, such as a key an operator generated or imported through the management API. An open
    /// vocabulary: each component names itself.
    /// </summary>
    // See ADR-1404.
    [MaxLength(SecretMaxLengths.ManagedBy)]
    public string? ManagedBy { get; init; }

    /// <summary>
    /// Gets the size, in bits, of the key material.
    /// For asymmetric keys, this is the size of the modulus.
    /// For symmetric keys, this is the size of the actual key material.
    /// For a shared secret, this is the size of its UTF-8 octets, whether it is stored as those octets or as a
    /// verifier.
    /// </summary>
    public required int KeySizeBits { get; init; }

    /// <summary>
    /// Gets the stored value: the base64url-encoded public key material, or the protected envelope of the private or
    /// symmetric key material or of a shared secret's verifier.
    /// </summary>
    [MaxLength(SecretMaxLengths.EncodedValue)]
    public required string EncodedValue { get; init; }

    /// <summary>
    /// Gets the base64url-encoded <c>SubjectPublicKeyInfo</c> DER of the public half of a private asymmetric key, so
    /// the public key is read without unprotecting <see cref="EncodedValue"/>; or <c>null</c> when the secret holds
    /// no private asymmetric key (its <see cref="EncodedValue"/> is symmetric or already public material).
    /// </summary>
    // See ADR-1268.
    [MaxLength(SecretMaxLengths.PublicKey)]
    public string? PublicKey { get; init; }

    /// <summary>
    /// Returns the secret's resource type and identifier, never its key material.
    /// </summary>
    /// <returns>The secret's resource type and identifier.</returns>
    public override string ToString() => $"{ResourceType}:{SecretId}";
}
