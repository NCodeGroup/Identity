using System.Globalization;
using Microsoft.CodeAnalysis;
using Xunit;

namespace NCode.Identity.Analyzers;

public class AutoPropertyAnalyzerTests
{
    private static async Task AssertReportsSingleFieldAsync(string source, string fieldName)
    {
        var diagnostics = await AnalyzerHarness.AnalyzeAsync(source, CancellationToken.None);

        var diagnostic = Assert.Single(diagnostics);
        Assert.Equal("NCID0001", diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Contains($"'{fieldName}'", diagnostic.GetMessage(CultureInfo.InvariantCulture));
    }

    #region Initialize

    [Fact]
    public async Task Initialize_InstanceField_ReportsField()
    {
        await AssertReportsSingleFieldAsync(
            "class C { private int _count; public int Next() => ++_count; }",
            "_count"
        );
    }

    [Fact]
    public async Task Initialize_StaticReadonlyField_ReportsField()
    {
        await AssertReportsSingleFieldAsync(
            "static class C { private static readonly string Name = \"n\"; public static string Get() => Name; }",
            "Name"
        );
    }

    [Fact]
    public async Task Initialize_StaticField_ReportsField()
    {
        await AssertReportsSingleFieldAsync(
            "static class C { private static int _calls; public static int Next() => ++_calls; }",
            "_calls"
        );
    }

    [Fact]
    public async Task Initialize_FieldMappedToHandWrittenFile_ReportsField()
    {
        await AssertReportsSingleFieldAsync(
            "// <auto-generated/>\nclass C\n{\n#line 4 \"Page.razor\"\n    private int _count;\n#line default\n    public int Next() => ++_count;\n}",
            "_count"
        );
    }

    [Fact]
    public async Task Initialize_ReadonlyStructMemberCall_ReportsField()
    {
        await AssertReportsSingleFieldAsync(
            "class C { private System.DateTime _when; public string Text() => _when.ToString(); }",
            "_when"
        );
    }

    [Fact]
    public async Task Initialize_TwoFields_ReportsEachField()
    {
        var diagnostics = await AnalyzerHarness.AnalyzeAsync(
            "class C { private int _a; private string _b = \"\"; public string Get() => _b + _a; }",
            CancellationToken.None
        );

        Assert.Equal(2, diagnostics.Length);
        Assert.All(diagnostics, diagnostic => Assert.Equal("NCID0001", diagnostic.Id));
        var ordered = diagnostics
            .OrderBy(diagnostic => diagnostic.Location.SourceSpan.Start)
            .ToList();
        Assert.Contains("'_a'", ordered[0].GetMessage(CultureInfo.InvariantCulture));
        Assert.Contains("'_b'", ordered[1].GetMessage(CultureInfo.InvariantCulture));
    }

    #endregion

    #region SupportedDiagnostics

    [Fact]
    public void SupportedDiagnostics_Rule_IsEnabledError()
    {
        var descriptor = Assert.Single(new AutoPropertyAnalyzer().SupportedDiagnostics);

        Assert.Equal("NCID0001", descriptor.Id);
        Assert.Equal(DiagnosticSeverity.Error, descriptor.DefaultSeverity);
        Assert.True(descriptor.IsEnabledByDefault);
        Assert.Contains(WellKnownDiagnosticTags.CompilationEnd, descriptor.CustomTags);
    }

    #endregion
}
